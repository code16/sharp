<?php

namespace Code16\Sharp\Utils\Uploads;

use Closure;
use Code16\Sharp\Form\Fields\Embeds\SharpFormEditorEmbed;
use Code16\Sharp\Form\Fields\Formatters\UploadFormatter;
use Code16\Sharp\Form\Fields\SharpFormEditorField;
use Code16\Sharp\Form\Fields\SharpFormField;
use Code16\Sharp\Form\Fields\SharpFormListField;
use Code16\Sharp\Utils\Fields\Formatters\FormatsHtmlContent;
use DOMElement;
use Illuminate\Support\Str;
use Illuminate\Validation\ValidationException;

/**
 * Embed data (and the editor HTML it may contain) lives on the client between the form
 * rendering and its submission, and is sent back to the embed endpoints. Existing files
 * referenced in this data must only be trusted (and re-signed / transformed into signed URLs)
 * if they carry a valid path_signature, generated by the server from trusted data.
 */
class UploadPathGuard
{
    use FormatsHtmlContent;

    /**
     * Signs every existing file referenced in embed data coming from a trusted source (eg. the database).
     */
    public function signEmbedData(SharpFormEditorEmbed $embed, array $data): array
    {
        return $this->walkEmbedData($embed, $data, fn (array $file) => $this->signFile($file));
    }

    /**
     * Ensures every existing file referenced in embed data sent by the client carries a valid signature.
     *
     * @throws ValidationException
     */
    public function ensureEmbedDataIsTrusted(SharpFormEditorEmbed $embed, array $data): array
    {
        return $this->walkEmbedData($embed, $data, fn (array $file, string $attribute) => $this->ensureFileIsTrusted($attribute, $file));
    }

    /**
     * Ensures every existing file referenced in a field value sent by the client carries a valid signature.
     *
     * @throws ValidationException
     */
    public function ensureFieldValueIsTrusted(SharpFormField $field, string $attribute, mixed $value): mixed
    {
        return $this->walkFieldValue($field, $attribute, $value, fn (array $file, string $attribute) => $this->ensureFileIsTrusted($attribute, $file));
    }

    public function signFile(array $file): array
    {
        if ($file['uploaded'] ?? false) {
            unset($file['path_signature']);

            return $file;
        }

        $path = $file['file_name'] ?? $file['path'] ?? null;

        if (! UploadPathSignature::enabled() || ! is_string($path)) {
            return $file;
        }

        $file['path_signature'] = UploadPathSignature::make(
            is_string($file['disk'] ?? null) ? $file['disk'] : null,
            $path
        );

        return $file;
    }

    protected function ensureFileIsTrusted(string $attribute, array $file): array
    {
        if ($file['uploaded'] ?? false) {
            // A newly uploaded file is only referenced by its name in the temporary directory
            unset($file['path'], $file['file_name'], $file['disk'], $file['path_signature']);

            return $file;
        }

        if (! UploadPathSignature::enabled()) {
            return $file;
        }

        $disk = $file['disk'] ?? null;
        $path = $file['file_name'] ?? $file['path'] ?? null;

        if ($disk === null && $path === null) {
            return $file;
        }

        if (! UploadPathSignature::check($file['path_signature'] ?? null, $disk, $path)) {
            throw ValidationException::withMessages([
                $attribute => trans('sharp::errors.invalid_file_signature'),
            ]);
        }

        return $file;
    }

    protected function walkEmbedData(SharpFormEditorEmbed $embed, array $data, Closure $onFile): array
    {
        foreach ($embed->getBuiltFields() as $fieldKey => $field) {
            if (array_key_exists($fieldKey, $data)) {
                $data[$fieldKey] = $this->walkFieldValue($field, $fieldKey, $data[$fieldKey], $onFile);
            }
        }

        return $data;
    }

    protected function walkFieldValue(SharpFormField $field, string $attribute, mixed $value, Closure $onFile): mixed
    {
        if ($field->formatter() instanceof UploadFormatter) {
            return is_array($value) ? $onFile($value, $attribute) : $value;
        }

        if ($field instanceof SharpFormListField) {
            return is_array($value)
                ? collect($value)
                    ->map(function ($item) use ($field, $attribute, $onFile) {
                        if (! is_array($item)) {
                            return $item;
                        }

                        foreach ($item as $itemKey => $itemValue) {
                            if ($itemField = $field->findItemFormFieldByKey((string) $itemKey)) {
                                $item[$itemKey] = $this->walkFieldValue($itemField, $attribute, $itemValue, $onFile);
                            }
                        }

                        return $item;
                    })
                    ->all()
                : $value;
        }

        if ($field instanceof SharpFormEditorField) {
            return $this->walkEditorValue($field, $attribute, $value, $onFile);
        }

        return $value;
    }

    protected function walkEditorValue(SharpFormEditorField $field, string $attribute, mixed $value, Closure $onFile): mixed
    {
        if (is_string($value)) {
            return $this->walkEditorHtml($field, $attribute, $value, $onFile);
        }

        if (! is_array($value)) {
            return $value;
        }

        if (array_key_exists('text', $value) || array_key_exists('uploads', $value) || array_key_exists('embeds', $value)) {
            // Editor value as sent by the front: ['text' => ..., 'uploads' => [...], 'embeds' => [...]]
            if (isset($value['text'])) {
                $value['text'] = $this->walkEditorValue($field, $attribute, $value['text'], $onFile);
            }

            if (isset($value['uploads']) && is_array($value['uploads'])) {
                foreach ($value['uploads'] as $key => $upload) {
                    if (is_array($upload['file'] ?? null)) {
                        $value['uploads'][$key]['file'] = $onFile($upload['file'], $attribute);
                    }
                }
            }

            if (isset($value['embeds']) && is_array($value['embeds'])) {
                foreach ($value['embeds'] as $embedKey => $embedsData) {
                    if (! ($embed = $field->embeds()->get($embedKey)) || ! is_array($embedsData)) {
                        continue;
                    }
                    foreach ($embedsData as $key => $embedData) {
                        if (is_array($embedData)) {
                            $value['embeds'][$embedKey][$key] = $this->walkEmbedData($embed, $embedData, $onFile);
                        }
                    }
                }
            }

            return $value;
        }

        // Localized value
        return collect($value)
            ->map(fn ($localizedValue) => $this->walkEditorValue($field, $attribute, $localizedValue, $onFile))
            ->all();
    }

    protected function walkEditorHtml(SharpFormEditorField $field, string $attribute, string $html, Closure $onFile): string
    {
        if (! str_contains($html, '<')) {
            return $html;
        }

        $domDocument = $this->parseHtml($html);
        $changed = false;

        foreach (['x-sharp-image', 'x-sharp-file'] as $tagName) {
            foreach (iterator_to_array($domDocument->getElementsByTagName($tagName)) as $element) {
                /** @var DOMElement $element */
                $file = json_decode($element->getAttribute('file'), true);
                if (is_array($file) && ($walked = $onFile($file, $attribute)) !== $file) {
                    $element->setAttribute('file', json_encode($walked));
                    $changed = true;
                }
            }
        }

        foreach ($field->embeds() as $embed) {
            foreach (iterator_to_array($domDocument->getElementsByTagName($embed->tagName())) as $element) {
                /** @var DOMElement $element */
                foreach ($embed->getBuiltFields() as $fieldKey => $embedField) {
                    if ($fieldKey === 'slot') {
                        if ($embedField instanceof SharpFormEditorField) {
                            $innerHtml = $this->getInnerHtml($element);
                            $walked = $this->walkEditorHtml($embedField, $attribute, $innerHtml, $onFile);
                            if ($walked !== $innerHtml) {
                                $this->setInnerHtml($element, $walked);
                                $changed = true;
                            }
                        }

                        continue;
                    }

                    $attributeName = Str::kebab($fieldKey);
                    if (! $element->hasAttribute($attributeName)) {
                        continue;
                    }

                    $attributeValue = $element->getAttribute($attributeName);
                    $decoded = json_decode($attributeValue, true);
                    $value = json_last_error() === JSON_ERROR_NONE ? $decoded : $attributeValue;
                    $walked = $this->walkFieldValue($embedField, $attribute, $value, $onFile);

                    if ($walked !== $value) {
                        $element->setAttribute($attributeName, is_array($walked) ? json_encode($walked) : $walked);
                        $changed = true;
                    }
                }
            }
        }

        return $changed ? $this->toHtml($domDocument) : $html;
    }
}
